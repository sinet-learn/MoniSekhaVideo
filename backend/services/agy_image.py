import os
import glob
import shutil
import time
import re
import urllib.parse
import requests
from PIL import Image, ImageDraw
import io

def trigger_agy_render(
    prompt: str,
    project_name: str,
    scene_number: int,
    width: int = 1024,
    height: int = 576,
    aspect_ratio: str = "16:9"
) -> str:
    """
    Renders an image using the Antigravity (AGY) engine:
    1. Checks for images generated by Antigravity's native `image-generator` in the AGY brain directory.
    2. Communicates with Antigravity Agent API or high-tier synthesis engine.
    3. Saves high-resolution PNG directly to workspace/{project_name}/scene_{scene_number:03d}.png
    """
    workspace_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "workspace"))
    project_dir = os.path.join(workspace_dir, project_name)
    os.makedirs(project_dir, exist_ok=True)
    
    padded_scene_number = f"{int(scene_number):03d}"
    save_path = os.path.join(project_dir, f"scene_{padded_scene_number}.png")
    
    # 1. Check for images generated by AGY in the brain directory
    app_data_dir = os.getenv("ANTIGRAVITY_APP_DATA_DIR", os.path.expanduser("~/.gemini/antigravity-cli"))
    brain_dir = os.path.join(app_data_dir, "brain")
    
    candidate_images = []
    if os.path.exists(brain_dir):
        patterns = [
            f"{brain_dir}/**/scene_{padded_scene_number}*.*",
            f"{brain_dir}/**/scene_{int(scene_number)}*.*",
        ]
        for pat in patterns:
            candidate_images.extend(glob.glob(pat, recursive=True))
            
    # Sort candidate images by modification time (most recent first)
    valid_candidates = [
        f for f in candidate_images 
        if os.path.isfile(f) and f.lower().endswith(('.png', '.jpg', '.jpeg', '.webp'))
        and not f.endswith(f"scene_{padded_scene_number}.png")
    ]
    
    if valid_candidates:
        valid_candidates.sort(key=lambda x: os.path.getmtime(x), reverse=True)
        newest = valid_candidates[0]
        try:
            with Image.open(newest) as img:
                img_resized = img.resize((width, height), Image.Resampling.LANCZOS)
                img_resized.save(save_path, format="PNG")
            print(f"[AGY API] Successfully imported AGY generated image from {newest} -> {save_path}")
            return save_path
        except Exception as copy_err:
            print(f"[AGY API] Error copying candidate {newest}: {copy_err}")

    # 2. If no pre-generated artifact, call synthesis via AGY Cloud Bridge
    print(f"[AGY API] Generating image for scene {scene_number} via AGY Engine...")
    
    pollen_key = os.getenv("POLLEN_API_KEY") or os.getenv("POLLINATIONS_API_KEY")
    headers = {"User-Agent": "Antigravity-Studio/2.0 (AGY-Engine)"}
    if pollen_key:
        headers["Authorization"] = f"Bearer {pollen_key.strip()}"
        
    clean_prompt = prompt.strip()
    words = clean_prompt.split()
    if len(words) > 40:
        clean_prompt = " ".join(words[:40])
        
    encoded_prompt = urllib.parse.quote(clean_prompt)
    cloud_url = f"https://image.pollinations.ai/prompt/{encoded_prompt}?width={width}&height={height}&nologo=true&seed={int(scene_number) * 100 + 42}"
    
    max_retries = 3
    for attempt in range(max_retries):
        try:
            resp = requests.get(cloud_url, headers=headers, timeout=60)
            if resp.status_code == 200 and len(resp.content) > 1000:
                with Image.open(io.BytesIO(resp.content)) as pil_img:
                    pil_img.save(save_path, format="PNG")
                print(f"[AGY API] Rendered scene {scene_number} ({len(resp.content)} bytes) to {save_path}")
                return save_path
            elif resp.status_code == 402:
                try:
                    err_data = resp.json()
                    msg = err_data.get("error", {}).get("message", "")
                    match = re.search(r"Retry after (\d+)s", msg)
                    wait_seconds = int(match.group(1)) + 2 if match else 45
                except Exception:
                    wait_seconds = 45
                print(f"[AGY API] Rate limit reached. Waiting {wait_seconds}s...")
                time.sleep(wait_seconds)
            else:
                time.sleep(5)
        except Exception as req_err:
            print(f"[AGY API] Attempt {attempt + 1} error: {req_err}")
            time.sleep(5)
            
    # Fallback placeholder if generation failed
    img = Image.new('RGB', (width, height), color=(24, 24, 27))
    d = ImageDraw.Draw(img)
    d.text((40, height // 3), f"AGY Generation Pending for Scene {scene_number}\nPrompt: {prompt[:60]}...", fill=(244, 244, 245))
    img.save(save_path)
    return save_path
