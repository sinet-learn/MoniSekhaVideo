import os
import tempfile
import subprocess
import imageio_ffmpeg
from typing import Dict, Any, Optional

ASPECT_RATIO_DIMENSIONS = {
    "16:9": (1920, 1080),
    "9:16": (1080, 1920),
    "1:1": (1080, 1080),
    "4:3": (1440, 1080),
    "2:3": (1080, 1620),
}

def get_motion_filter(motion_type: str, frames: int, out_w: int, out_h: int, fps: int = 30) -> str:
    """
    Constructs an FFmpeg zoompan filter string for cinematic camera motion.
    """
    base_filter = f"scale={out_w}:{out_h}:force_original_aspect_ratio=increase,crop={out_w}:{out_h}"
    
    if motion_type == "zoom_out":
        zp = (
            f"zoompan=z='if(lte(zoom,1.0),1.20,max(1.001,zoom-0.0012))':"
            f"d={frames}:x='iw/2-(iw/zoom/2)':y='ih/2-(ih/zoom/2)':s={out_w}x{out_h}:fps={fps}"
        )
    elif motion_type == "pan_left":
        zp = (
            f"zoompan=z=1.16:d={frames}:"
            f"x='if(lte(on,1),(iw-iw/zoom),max(0,x-1.5))':y='ih/2-(ih/zoom/2)':s={out_w}x{out_h}:fps={fps}"
        )
    elif motion_type == "pan_right":
        zp = (
            f"zoompan=z=1.16:d={frames}:"
            f"x='if(lte(on,1),0,min(iw-iw/zoom,x+1.5))':y='ih/2-(ih/zoom/2)':s={out_w}x{out_h}:fps={fps}"
        )
    else:
        # Default zoom_in
        zp = (
            f"zoompan=z='min(zoom+0.0012,1.20)':"
            f"d={frames}:x='iw/2-(iw/zoom/2)':y='ih/2-(ih/zoom/2)':s={out_w}x{out_h}:fps={fps}"
        )

    return f"{base_filter},{zp},format=yuv420p"

def render_camera_motion_clip(
    image_path: str,
    output_path: str,
    duration: float = 4.0,
    motion_type: str = "zoom_in",
    aspect_ratio: str = "16:9",
    fps: int = 30
) -> str:
    """
    Renders a high-resolution MP4 video clip from a still image with smooth camera motion.
    """
    if not os.path.exists(image_path):
        raise FileNotFoundError(f"Source image not found: {image_path}")

    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    ffmpeg_exe = imageio_ffmpeg.get_ffmpeg_exe()
    out_w, out_h = ASPECT_RATIO_DIMENSIONS.get(aspect_ratio, (1920, 1080))
    
    frames = max(1, int(round(duration * fps)))
    vf = get_motion_filter(motion_type, frames, out_w, out_h, fps)

    descriptor, temporary = tempfile.mkstemp(suffix=".mp4", dir=os.path.dirname(output_path))
    os.close(descriptor)
    cmd = [
        ffmpeg_exe, "-y",
        "-loop", "1",
        "-i", image_path,
        "-t", f"{duration:.3f}",
        "-vf", vf,
        "-c:v", "libx264",
        "-pix_fmt", "yuv420p",
        "-preset", "faster",
        "-tune", "stillimage",
        temporary
    ]

    try:
        res = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
        if res.returncode != 0:
            raise Exception(f"FFmpeg motion rendering failed: {res.stderr}")
        os.replace(temporary, output_path)
    finally:
        if os.path.exists(temporary):
            os.remove(temporary)

    return output_path

def prepare_scene_chunk(
    image_path: str,
    output_chunk_path: str,
    duration: float,
    motion_type: str = "zoom_in",
    aspect_ratio: str = "16:9",
    custom_video_path: Optional[str] = None,
    fps: int = 30
) -> str:
    """
    Renders an individual scene video chunk matching its exact voiceover duration:
    - If custom AI video exists: scales, pads, and loops/trims it.
    - If motion_type is 'none' / 'static': renders a static video hold.
    - Otherwise: renders cinematic Pan & Zoom camera motion.
    """
    os.makedirs(os.path.dirname(output_chunk_path), exist_ok=True)
    ffmpeg_exe = imageio_ffmpeg.get_ffmpeg_exe()
    out_w, out_h = ASPECT_RATIO_DIMENSIONS.get(aspect_ratio, (1920, 1080))
    
    if custom_video_path and os.path.exists(custom_video_path):
        vf = f"scale={out_w}:{out_h}:force_original_aspect_ratio=decrease,pad={out_w}:{out_h}:(ow-iw)/2:(oh-ih)/2,format=yuv420p"
        cmd = [
            ffmpeg_exe, "-y",
            "-stream_loop", "-1",
            "-i", custom_video_path,
            "-t", f"{duration:.3f}",
            "-vf", vf,
            "-an",  # Narration is mixed separately; omit audio generated by Flow.
            "-c:v", "libx264",
            "-pix_fmt", "yuv420p",
            "-preset", "faster",
            output_chunk_path
        ]
        res = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
        if res.returncode == 0:
            return output_chunk_path

    if motion_type in ("none", "static"):
        vf = f"scale={out_w}:{out_h}:force_original_aspect_ratio=decrease,pad={out_w}:{out_h}:(ow-iw)/2:(oh-ih)/2,format=yuv420p"
        cmd = [
            ffmpeg_exe, "-y",
            "-loop", "1",
            "-i", image_path,
            "-t", f"{duration:.3f}",
            "-vf", vf,
            "-c:v", "libx264",
            "-pix_fmt", "yuv420p",
            "-preset", "faster",
            "-tune", "stillimage",
            output_chunk_path
        ]
        subprocess.run(cmd, check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        return output_chunk_path

    return render_camera_motion_clip(image_path, output_chunk_path, duration, motion_type, aspect_ratio, fps)

def get_scene_animation_info(workspace_dir: str, project_slug: str, scene_number: int) -> Dict[str, Any]:
    """
    Checks if a custom AI video or camera motion clip exists for this scene.
    """
    proj_dir = os.path.join(workspace_dir, project_slug)
    ai_video_name = f"scene_{scene_number:03d}_video.mp4"
    motion_video_name = f"scene_{scene_number:03d}_motion.mp4"
    
    ai_path = os.path.join(proj_dir, ai_video_name)
    motion_path = os.path.join(proj_dir, motion_video_name)

    has_ai_video = os.path.exists(ai_path) and os.path.getsize(ai_path) > 1000
    has_motion_video = os.path.exists(motion_path) and os.path.getsize(motion_path) > 1000

    active_video_path = None
    video_type = None

    if has_ai_video:
        active_video_path = f"{project_slug}/{ai_video_name}"
        video_type = "ai_video"
    elif has_motion_video:
        active_video_path = f"{project_slug}/{motion_video_name}"
        video_type = "camera_motion"

    return {
        "has_video": bool(active_video_path),
        "video_path": active_video_path,
        "video_type": video_type,
        "has_ai_video": has_ai_video,
        "has_motion_video": has_motion_video
    }
